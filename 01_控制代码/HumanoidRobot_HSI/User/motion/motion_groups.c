const MotionGroup_t *MotionGroups_Get(MotionId_t id)
{
    if ((uint8_t)id >= (uint8_t)motion_group_count)
    {
        return &s_groups[motion_stand];
    }

    return &s_groups[id];
}

MotionId_t MotionGroups_FromQr(uint8_t qrNumber)
{
    static const MotionId_t qrActions[6] =
    {
        motion_qr_left_arm,
        motion_qr_right_arm,
        motion_qr_left_leg,
        motion_qr_right_leg,
        motion_qr_both_arms,
        motion_qr_head_shake
    };

    if ((qrNumber < 1U) || (qrNumber > 6U))
    {
        return motion_stand;
    }

    return qrActions[qrNumber - 1U];
}

